package codews

import "strings"

// FishCompletion 打印 fish 补全脚本。候选仍由 projects/branches 现查，这里不往配置目录写文件。
func FishCompletion() string {
	lines := []string{
		"complete -c code-ws -f",
		"function __code_ws_projects",
		"  code-ws projects 2>/dev/null",
		"end",
		"function __code_ws_from",
		"  set -l token (commandline -ct)",
		"  if string match -q -- '*=*' $token",
		"    set -l repo (string split -f1 = -- $token)",
		"    for ref in (code-ws branches $repo 2>/dev/null)",
		"      printf '%s=%s\\n' $repo $ref",
		"    end",
		"    return",
		"  end",
		"  set -l tokens (commandline -opc)",
		"  set -l profile ''",
		"  set -l idx 1",
		"  while test $idx -le (count $tokens)",
		"    if test $tokens[$idx] = -t; or test $tokens[$idx] = --template",
		"      set profile $tokens[(math $idx + 1)]",
		"    end",
		"    set idx (math $idx + 1)",
		"  end",
		"  if test -n \"$profile\"",
		"    for repo in (code-ws projects -t $profile 2>/dev/null)",
		"      printf '%s=\\n' $repo",
		"    end",
		"    return",
		"  end",
		"  if contains -- sync $tokens",
		"    for repo in (code-ws projects --workspace 2>/dev/null)",
		"      printf '%s=\\n' $repo",
		"    end",
		"    return",
		"  end",
		"  for repo in (code-ws projects 2>/dev/null)",
		"    printf '%s=\\n' $repo",
		"  end",
		"end",
		"function __code_ws_needs_init_project",
		"  set -l tokens (commandline -opc)",
		"  test (count $tokens) -eq 3",
		"  and test $tokens[2] = init",
		"end",
		"complete -c code-ws -s v -l verbose -d '打印 git 命令'",
		"complete -c code-ws -s c -l config -r -d '配置文件路径'",
		"complete -c code-ws -s t -l template -x -d 'profile 名称'",
		"complete -c code-ws -n '__fish_seen_subcommand_from init' -s p -l project -xa '(__code_ws_projects)' -d '仅初始化指定项目'",
		"complete -c code-ws -n '__fish_seen_subcommand_from init sync' -l from -xa '(__code_ws_from)' -d '合并目标 repo=branch'",
		"complete -c code-ws -n '__fish_use_subcommand' -xa 'init add remove sync destroy fork list projects branches config serve completion help' -d '功能命令'",
		"complete -c code-ws -n '__code_ws_needs_init_project' -ka '(__code_ws_projects)' -d '项目名'",
		"complete -c code-ws -n '__fish_seen_subcommand_from add remove' -xa 'project' -d '项目操作'",
		"complete -c code-ws -n '__fish_seen_subcommand_from project' -ka '(__code_ws_projects)' -d '项目名'",
		"complete -c code-ws -n '__fish_seen_subcommand_from sync' -xa 'master' -d '同步主分支'",
		"complete -c code-ws -n '__fish_seen_subcommand_from projects' -s t -l template -d '只列出 profile 中的项目'",
		"complete -c code-ws -n '__fish_seen_subcommand_from projects' -l workspace -d '只列出当前 workspace 的项目'",
		"complete -c code-ws -n '__fish_seen_subcommand_from branches' -ka '(__code_ws_projects)' -d '项目名'",
		"complete -c code-ws -n '__fish_seen_subcommand_from config' -xa 'check' -d '检查配置'",
		"complete -c code-ws -n '__fish_seen_subcommand_from completion' -xa 'fish' -d '生成 fish completion'",
		"complete -c code-ws -n '__fish_seen_subcommand_from serve' -l lan -d '监听 0.0.0.0 (默认)'",
		"complete -c code-ws -n '__fish_seen_subcommand_from serve' -l local -d '仅监听 127.0.0.1'",
		"complete -c code-ws -n '__fish_seen_subcommand_from serve' -l port -r -d '端口, 默认 7001, 占用则顺延'",
		"complete -c code-ws -n '__fish_seen_subcommand_from serve' -l no-watch -d '关闭文件变更自动刷新'",
		"complete -c code-ws -n '__fish_seen_subcommand_from serve' -l cf -d 'Quick Tunnel 临时公网地址'",
		"complete -c code-ws -n '__fish_seen_subcommand_from serve' -l cloudflare -d '同 --cf'",
	}
	return strings.Join(lines, "\n")
}
