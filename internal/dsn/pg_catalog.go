// runPgCatalog 在驱动里查 pg_catalog，不调用 pg_dump 或 psql。
func runPgCatalog(ctx context.Context, conn *pgx.Conn, spec PgCatalog) (QueryOut, error) {
	switch spec.Head {
	case "tables":
		return listTables(ctx, conn, spec)
	case "columns":
		return listColumns(ctx, conn, spec.Rel)
	default:
		return showDDL(ctx, conn, spec.Rel)
	}
}

func listTables(ctx context.Context, conn *pgx.Conn, spec PgCatalog) (QueryOut, error) {
	filters := []string{
		"table_type = 'BASE TABLE'",
		"table_schema NOT IN ('pg_catalog', 'information_schema')",
	}
	var params []any
	if spec.HasLike {
		params = append(params, spec.Like)
		filters = append(filters, fmt.Sprintf("table_name LIKE $%d", len(params)))
	}
	sql := `SELECT table_schema AS schema, table_name AS name
FROM information_schema.tables
WHERE ` + strings.Join(filters, " AND ") + `
ORDER BY table_schema, table_name`
	rows, err := conn.Query(ctx, sql, params...)
	if err != nil {
		return QueryOut{}, exitf(3, "%s", err.Error())
	}
	return pgRows(rows)
}

func listColumns(ctx context.Context, conn *pgx.Conn, rel string) (QueryOut, error) {
	oid, err := relOID(ctx, conn, rel)
	if err != nil {
		return QueryOut{}, err
	}
	sql := `SELECT
  a.attname AS name,
  pg_catalog.format_type(a.atttypid, a.atttypmod) AS type,
  CASE WHEN a.attnotnull THEN 'NO' ELSE 'YES' END AS nullable,
  CASE
    WHEN a.attidentity = 'a' THEN 'generated always as identity'
    WHEN a.attidentity = 'd' THEN 'generated by default as identity'
    WHEN a.attgenerated = 's' THEN pg_catalog.pg_get_expr(ad.adbin, ad.adrelid)
    ELSE pg_catalog.pg_get_expr(ad.adbin, ad.adrelid)
  END AS "default",
  CASE WHEN EXISTS (
    SELECT 1 FROM pg_catalog.pg_index i
    WHERE i.indrelid = a.attrelid AND i.indisprimary AND a.attnum = ANY (i.indkey)
  ) THEN 'PRI' ELSE '' END AS key,
  pg_catalog.col_description(a.attrelid, a.attnum) AS comment
FROM pg_catalog.pg_attribute a
LEFT JOIN pg_catalog.pg_attrdef ad
  ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
WHERE a.attrelid = $1::oid
  AND a.attnum > 0
  AND NOT a.attisdropped
ORDER BY a.attnum`
	rows, err := conn.Query(ctx, sql, oid)
	if err != nil {
		return QueryOut{}, exitf(3, "%s", err.Error())
	}
	return pgRows(rows)
}

func showDDL(ctx context.Context, conn *pgx.Conn, rel string) (QueryOut, error) {
	oid, err := relOID(ctx, conn, rel)
	if err != nil {
		return QueryOut{}, err
	}
	info, err := relInfo(ctx, conn, oid)
	if err != nil {
		return QueryOut{}, err
	}
	var ddl string
	switch info.relkind {
	case "v", "m":
		ddl, err = viewDDL(ctx, conn, oid, info)
	case "r", "p":
		ddl, err = tableDDL(ctx, conn, oid, info)
	default:
		return QueryOut{}, exitf(3, "not a table: %s", rel)
	}
	if err != nil {
		return QueryOut{}, err
	}
	return QueryOut{Columns: []string{"ddl"}, Rows: []map[string]any{{"ddl": ddl}}}, nil
}

func relOID(ctx context.Context, conn *pgx.Conn, rel string) (string, error) {
	var oid *string
	err := conn.QueryRow(ctx, "SELECT to_regclass($1)::oid::text", rel).Scan(&oid)
	if err != nil {
		return "", exitf(3, "%s", err.Error())
	}
	if oid == nil || *oid == "" {
		return "", exitf(3, "table not found: %s", rel)
	}
	return *oid, nil
}

type relRow struct {
	nspname        string
	relname        string
	relkind        string
	relpersistence string
	comment        *string
	partkey        *string
}

func relInfo(ctx context.Context, conn *pgx.Conn, oid string) (relRow, error) {
	sql := `SELECT
  n.nspname,
  c.relname,
  c.relkind,
  c.relpersistence,
  pg_catalog.obj_description(c.oid, 'pg_class') AS comment,
  pg_catalog.pg_get_partkeydef(c.oid) AS partkey
FROM pg_catalog.pg_class c
JOIN pg_catalog.pg_namespace n ON n.oid = c.relnamespace
WHERE c.oid = $1::oid`
	var row relRow
	err := conn.QueryRow(ctx, sql, oid).Scan(
		&row.nspname, &row.relname, &row.relkind, &row.relpersistence, &row.comment, &row.partkey,
	)
	if err != nil {
		return relRow{}, exitf(3, "table not found")
	}
	return row, nil
}

func viewDDL(ctx context.Context, conn *pgx.Conn, oid string, info relRow) (string, error) {
	var def *string
	err := conn.QueryRow(ctx, "SELECT pg_catalog.pg_get_viewdef($1::oid, true)", oid).Scan(&def)
	if err != nil || def == nil {
		return "", exitf(3, "view definition not found")
	}
	kind := "VIEW"
	if info.relkind == "m" {
		kind = "MATERIALIZED VIEW"
	}
	qn := qualName(info.nspname, info.relname)
	body := *def
	if !strings.HasSuffix(body, ";") {
		body += ";"
	}
	parts := []string{"CREATE " + kind + " " + qn + " AS", body}
	appendComment(&parts, qn, info.comment)
	return strings.Join(parts, "\n"), nil
}

func tableDDL(ctx context.Context, conn *pgx.Conn, oid string, info relRow) (string, error) {
	cols, err := colDefs(ctx, conn, oid)
	if err != nil {
		return "", err
	}
	cons, err := conDefs(ctx, conn, oid)
	if err != nil {
		return "", err
	}
	idx, err := indexDefs(ctx, conn, oid)
	if err != nil {
		return "", err
	}
	unlogged := ""
	if info.relpersistence == "u" {
		unlogged = "UNLOGGED "
	}
	qn := qualName(info.nspname, info.relname)
	lines := append(cols, cons...)
	for i, line := range lines {
		lines[i] = "  " + line
	}
	create := "CREATE " + unlogged + "TABLE " + qn + " (\n" + strings.Join(lines, ",\n") + "\n)"
	if info.partkey != nil && *info.partkey != "" {
		create += " PARTITION BY " + *info.partkey
	}
	create += ";"
	parts := []string{create}
	for _, def := range idx {
		parts = append(parts, def+";")
	}
	appendComment(&parts, qn, info.comment)
	comments, err := colComments(ctx, conn, oid, qn)
	if err != nil {
		return "", err
	}
	parts = append(parts, comments...)
	return strings.Join(parts, "\n"), nil
}

type colRow struct {
	name      string
	typ       string
	notnull   bool
	def       *string
	identity  string
	generated string
}

func colDefs(ctx context.Context, conn *pgx.Conn, oid string) ([]string, error) {
	sql := `SELECT
  a.attname,
  pg_catalog.format_type(a.atttypid, a.atttypmod),
  a.attnotnull,
  pg_catalog.pg_get_expr(ad.adbin, ad.adrelid),
  a.attidentity,
  a.attgenerated
FROM pg_catalog.pg_attribute a
LEFT JOIN pg_catalog.pg_attrdef ad
  ON ad.adrelid = a.attrelid AND ad.adnum = a.attnum
WHERE a.attrelid = $1::oid
  AND a.attnum > 0
  AND NOT a.attisdropped
ORDER BY a.attnum`
	rows, err := conn.Query(ctx, sql, oid)
	if err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	defer rows.Close()
	var lines []string
	for rows.Next() {
		var row colRow
		if err := rows.Scan(&row.name, &row.typ, &row.notnull, &row.def, &row.identity, &row.generated); err != nil {
			return nil, exitf(3, "%s", err.Error())
		}
		lines = append(lines, colLine(row))
	}
	if err := rows.Err(); err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	return lines, nil
}

func colLine(row colRow) string {
	bits := []string{quoteIdent(row.name), row.typ}
	switch {
	case row.identity == "a":
		bits = append(bits, "GENERATED ALWAYS AS IDENTITY")
	case row.identity == "d":
		bits = append(bits, "GENERATED BY DEFAULT AS IDENTITY")
	case row.generated == "s" && row.def != nil && *row.def != "":
		bits = append(bits, "GENERATED ALWAYS AS ("+*row.def+") STORED")
	case row.def != nil && *row.def != "":
		bits = append(bits, "DEFAULT "+*row.def)
	}
	if row.notnull {
		bits = append(bits, "NOT NULL")
	}
	return strings.Join(bits, " ")
}

func conDefs(ctx context.Context, conn *pgx.Conn, oid string) ([]string, error) {
	sql := `SELECT conname, pg_catalog.pg_get_constraintdef(oid, true)
FROM pg_catalog.pg_constraint
WHERE conrelid = $1::oid
  AND contype IN ('p', 'u', 'c', 'f', 'x')
ORDER BY CASE contype WHEN 'p' THEN 0 WHEN 'u' THEN 1 WHEN 'c' THEN 2 WHEN 'f' THEN 3 ELSE 4 END, conname`
	rows, err := conn.Query(ctx, sql, oid)
	if err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	defer rows.Close()
	var lines []string
	for rows.Next() {
		var name, def string
		if err := rows.Scan(&name, &def); err != nil {
			return nil, exitf(3, "%s", err.Error())
		}
		lines = append(lines, "CONSTRAINT "+quoteIdent(name)+" "+def)
	}
	if err := rows.Err(); err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	return lines, nil
}

func indexDefs(ctx context.Context, conn *pgx.Conn, oid string) ([]string, error) {
	sql := `SELECT pg_catalog.pg_get_indexdef(i.indexrelid, 0, true)
FROM pg_catalog.pg_index i
JOIN pg_catalog.pg_class ic ON ic.oid = i.indexrelid
WHERE i.indrelid = $1::oid
  AND NOT i.indisprimary
  AND NOT EXISTS (
    SELECT 1 FROM pg_catalog.pg_constraint c
    WHERE c.conrelid = i.indrelid AND c.conindid = i.indexrelid
  )
ORDER BY ic.relname`
	rows, err := conn.Query(ctx, sql, oid)
	if err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	defer rows.Close()
	var lines []string
	for rows.Next() {
		var def string
		if err := rows.Scan(&def); err != nil {
			return nil, exitf(3, "%s", err.Error())
		}
		lines = append(lines, def)
	}
	if err := rows.Err(); err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	return lines, nil
}

func colComments(ctx context.Context, conn *pgx.Conn, oid, qn string) ([]string, error) {
	sql := `SELECT a.attname, pg_catalog.col_description(a.attrelid, a.attnum)
FROM pg_catalog.pg_attribute a
WHERE a.attrelid = $1::oid
  AND a.attnum > 0
  AND NOT a.attisdropped
  AND pg_catalog.col_description(a.attrelid, a.attnum) IS NOT NULL
ORDER BY a.attnum`
	rows, err := conn.Query(ctx, sql, oid)
	if err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	defer rows.Close()
	var lines []string
	for rows.Next() {
		var name, comment string
		if err := rows.Scan(&name, &comment); err != nil {
			return nil, exitf(3, "%s", err.Error())
		}
		col := qn + "." + quoteIdent(name)
		lines = append(lines, "COMMENT ON COLUMN "+col+" IS "+sqlString(comment)+";")
	}
	if err := rows.Err(); err != nil {
		return nil, exitf(3, "%s", err.Error())
	}
	return lines, nil
}

func appendComment(parts *[]string, qn string, comment *string) {
	if comment != nil && *comment != "" {
		*parts = append(*parts, "COMMENT ON TABLE "+qn+" IS "+sqlString(*comment)+";")
	}
}

func qualName(schema, name string) string {
	return quoteIdent(schema) + "." + quoteIdent(name)
}

var plainIdent = regexp.MustCompile(`^[a-z_][a-z0-9_]*$`)

func quoteIdent(name string) string {
	if plainIdent.MatchString(name) {
		return name
	}
	return `"` + strings.ReplaceAll(name, `"`, `""`) + `"`
}

func sqlString(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "''") + "'"
}
